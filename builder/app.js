const form = document.getElementById("brief-form");
const briefField = document.getElementById("brief");
const consentField = document.getElementById("consent");
const submitButton = document.getElementById("submit-button");
const statusLine = document.getElementById("form-status");
const resultSection = document.getElementById("plan-result");
const count = document.getElementById("char-count");
let language = "ar";
let currentPlan = null;

function text(key) {
  return copy[language][key] ?? copy.en[key] ?? key;
}

function applyTokens(tokens) {
  const root = document.documentElement;
  const tokenValue = (group, name) => tokens?.[group]?.[name]?.value;
  const vars = {
    "--ui-bg": tokenValue("color", "background")?.primary,
    "--ui-surface": tokenValue("color", "surface")?.panel,
    "--ui-elevated": tokenValue("color", "surface")?.["panel-elevated"],
    "--ui-border": tokenValue("color", "border")?.default,
    "--ui-text": tokenValue("color", "text")?.primary,
    "--ui-muted": tokenValue("color", "text")?.muted,
    "--ui-accent": tokenValue("color", "accent")?.primary,
    "--ui-accent-2": tokenValue("color", "accent")?.secondary,
    "--ui-warning": tokenValue("color", "accent")?.warning,
    "--ui-font-ar": tokenValue("font", "family")?.arabic,
    "--ui-font-en": tokenValue("font", "family")?.english,
    "--ui-radius-sm": tokenValue("radius", "sm"),
    "--ui-radius-md": tokenValue("radius", "md"),
    "--ui-radius-lg": tokenValue("radius", "lg"),
    "--ui-radius-full": tokenValue("radius", "full"),
  };
  for (const [name, value] of Object.entries(vars)) {
    if (typeof value === "string" && value.length < 160) root.style.setProperty(name, value);
  }
}

function setStatus(key, isError = false) {
  statusLine.dataset.statusKey = key;
  statusLine.textContent = text(key);
  statusLine.classList.toggle("error", isError);
}

function renderList(targetId, values, renderItem) {
  const list = document.getElementById(targetId);
  list.replaceChildren();
  const items = values.length ? values : [text("empty-list")];
  for (const value of items) {
    const item = document.createElement("li");
    if (renderItem) renderItem(item, value);
    else item.textContent = value;
    list.append(item);
  }
}

function renderPlan(plan) {
  document.getElementById("plan-title").textContent = plan.projectName;
  document.getElementById("plan-summary").textContent = plan.summary;
  renderList("plan-pages", plan.pages, (item, page) => {
    const name = document.createElement("strong");
    name.textContent = page.name;
    item.append(name, document.createTextNode(` — ${page.purpose}`));
  });
  renderList("plan-features", plan.features);
  renderList("plan-questions", plan.questions);
  renderList("plan-assumptions", plan.assumptions);
  document.getElementById("plan-milestone").textContent = plan.firstMilestone;
  resultSection.hidden = false;
}

function setLanguage(next) {
  language = next;
  document.documentElement.lang = next;
  document.documentElement.dir = next === "ar" ? "rtl" : "ltr";
  document.getElementById("language-toggle").textContent = next === "ar" ? "English" : "العربية";
  document.getElementById("language-toggle").setAttribute("aria-label", next === "ar" ? "Switch to English" : "التبديل إلى العربية");
  for (const node of document.querySelectorAll("[data-i18n]")) {
    const key = node.dataset.i18n;
    node.textContent = text(key);
  }
  briefField.placeholder = text("placeholder-brief");
  count.textContent = `${briefField.value.length} / 4000`;
  if (submitButton.disabled) submitButton.querySelector("span").textContent = text("submitting");
  if (statusLine.textContent) {
    const knownKey = statusLine.dataset.statusKey;
    if (knownKey) setStatus(knownKey, statusLine.classList.contains("error"));
  }
  if (currentPlan) renderPlan(currentPlan);
}

async function loadTokens() {
  try {
    const response = await fetch("/tokens.json", { headers: { Accept: "application/json" } });
    if (!response.ok) return;
    applyTokens(await response.json());
  } catch {
    // System color fallbacks keep the page readable when tokens cannot load.
  }
}

function errorKey(code) {
  if (code === "PLANNER_NOT_CONFIGURED") return "status-not-configured";
  if (code === "PLANNER_BUSY") return "status-busy";
  if (code === "PROVIDER_TIMEOUT") return "status-timeout";
  if (["PROVIDER_ERROR", "INVALID_PROVIDER_RESPONSE"].includes(code)) return "status-provider";
  if (code === "CONSENT_REQUIRED") return "status-consent";
  return "status-generic";
}

function showFailure(key) {
  resultSection.hidden = true;
  currentPlan = null;
  setStatus(key, true);
}

document.getElementById("language-toggle").addEventListener("click", () => setLanguage(language === "ar" ? "en" : "ar"));
briefField.addEventListener("input", () => {
  count.textContent = `${briefField.value.length} / 4000`;
  statusLine.textContent = "";
  statusLine.dataset.statusKey = "";
  statusLine.classList.remove("error");
});

for (const button of document.querySelectorAll("[data-example]")) {
  button.addEventListener("click", () => {
    briefField.value = text(`example-value-${button.dataset.example}`);
    briefField.dispatchEvent(new Event("input", { bubbles: true }));
    briefField.focus();
  });
}

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  if (!form.reportValidity()) return;
  if (briefField.value.trim().length < 20) return showFailure("status-short");
  if (briefField.value.length > 4000) return showFailure("status-length");
  if (!consentField.checked) return showFailure("status-consent");

  const requestLanguage = language;
  submitButton.disabled = true;
  submitButton.querySelector("span").textContent = text("submitting");
  form.setAttribute("aria-busy", "true");
  setStatus("status-ready");
  resultSection.hidden = true;

  try {
    const response = await fetch("/api/plan", {
      method: "POST",
      headers: { "Content-Type": "application/json", Accept: "application/json" },
      body: JSON.stringify({ brief: briefField.value.trim(), language: requestLanguage, consent: true }),
    });
    let payload;
    try { payload = await response.json(); } catch { payload = null; }
    if (!response.ok || !payload?.plan) return showFailure(errorKey(payload?.error));
    currentPlan = payload.plan;
    renderPlan(currentPlan);
    setStatus("status-success");
    const behavior = window.matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth";
    resultSection.scrollIntoView({ behavior, block: "start" });
  } catch {
    showFailure("status-generic");
  } finally {
    submitButton.disabled = false;
    submitButton.querySelector("span").textContent = text("submit");
    form.removeAttribute("aria-busy");
  }
});

document.getElementById("clear-plan").addEventListener("click", () => {
  currentPlan = null;
  resultSection.hidden = true;
  form.reset();
  count.textContent = "0 / 4000";
  setStatus("status-ready");
  briefField.focus();
});

setLanguage("ar");
loadTokens();
