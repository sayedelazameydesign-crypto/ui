#!/usr/bin/env node
// Artifact manifest — dataset/model state tracking for reproducibility.
//
//   node scripts/artifact-manifest.mjs --write    # (re)generate artifacts.manifest.json
//   node scripts/artifact-manifest.mjs --check    # fail on drift; used by the guard and CI
//   node scripts/artifact-manifest.mjs --json
//
// Large binaries belong in Git LFS (see .gitattributes); this manifest records the
// exact bytes of everything under the artifact roots so a checkout can be verified
// against the state that produced a result. Policy: docs/data/artifacts.md

import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const MANIFEST = "artifacts.manifest.json";
const ROOTS = ["data", "models", "public", "assets"];
const LFS_POINTER = "version https://git-lfs.github.com/spec/v1";

const argv = process.argv.slice(2);
const WRITE = argv.includes("--write");
const CHECK = argv.includes("--check");
const JSON_OUT = argv.includes("--json");

function walk(dir, acc = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === ".gitkeep" || entry.name.startsWith(".")) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, acc);
    else if (entry.isFile()) acc.push(full);
  }
  return acc;
}

function isLfsPointer(path) {
  try {
    return readFileSync(path, "utf8").slice(0, 64).startsWith(LFS_POINTER);
  } catch {
    return false;
  }
}

function scan() {
  const entries = [];
  for (const root of ROOTS) {
    if (!existsSync(root)) continue;
    for (const path of walk(root)) {
      const rel = relative(".", path).split(sep).join("/");
      const lfs = isLfsPointer(path);
      const bytes = lfs ? Number(/(?:^|\n)size (\d+)/.exec(readFileSync(path, "utf8"))?.[1] ?? 0) : statSync(path).size;
      const sha256 = lfs
        ? (/(?:^|\n)oid sha256:([a-f0-9]{64})/.exec(readFileSync(path, "utf8"))?.[1] ?? "")
        : createHash("sha256").update(readFileSync(path)).digest("hex");
      entries.push({ path: rel, bytes, sha256, lfs });
    }
  }
  return entries.sort((a, b) => a.path.localeCompare(b.path));
}

const entries = scan();
const manifest = {
  version: 1,
  description:
    "Dataset and model state for reproducibility. Generated by scripts/artifact-manifest.mjs — do not edit by hand.",
  roots: ROOTS,
  lfs: true,
  totals: { files: entries.length, bytes: entries.reduce((s, e) => s + e.bytes, 0) },
  entries,
};

if (WRITE) {
  writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`wrote ${MANIFEST}: ${entries.length} artifact(s), ${manifest.totals.bytes} bytes`);
  process.exit(0);
}

if (CHECK) {
  if (!existsSync(MANIFEST)) {
    console.log(`\x1b[31m✗\x1b[0m ${MANIFEST} is missing — run: node scripts/artifact-manifest.mjs --write`);
    process.exit(1);
  }
  const committed = JSON.parse(readFileSync(MANIFEST, "utf8"));
  const problems = [];
  const committedMap = new Map((committed.entries ?? []).map((e) => [e.path, e]));
  for (const entry of entries) {
    const known = committedMap.get(entry.path);
    if (!known) problems.push(`new artifact not in manifest: ${entry.path}`);
    else if (known.sha256 !== entry.sha256) problems.push(`content drift: ${entry.path}`);
    committedMap.delete(entry.path);
  }
  for (const path of committedMap.keys()) problems.push(`artifact missing from disk: ${path}`);

  if (problems.length) {
    for (const p of problems) console.log(`\x1b[31m✗\x1b[0m ${p}`);
    console.log("run: node scripts/artifact-manifest.mjs --write  (and commit the manifest)");
    process.exit(1);
  }
  console.log(`artifact manifest in sync (${entries.length} file(s), ${manifest.totals.bytes} bytes)`);
  process.exit(0);
}

if (JSON_OUT) console.log(JSON.stringify(manifest, null, 2));
else {
  console.log(`artifacts: ${manifest.totals.files} file(s), ${manifest.totals.bytes} bytes`);
  for (const root of ROOTS) {
    const count = entries.filter((e) => e.path.startsWith(`${root}/`)).length;
    console.log(`  ${root.padEnd(8)} ${count === 0 ? "empty (no artifacts yet)" : `${count} file(s)`}`);
  }
}
